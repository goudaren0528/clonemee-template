  var PEM_RE = /-----BEGIN [A-Z0-9 ]*-----/i;
  var AUTHORIZATION_RE = /\b(?:proxy-)?authorization\s*[:=：]\s*\S/i;
  var BEARER_RE = /\bbearer\s+[A-Za-z0-9._~+\/=-]{8,}/i;
  // BEGIN CREDENTIAL_ASSIGNMENT_RE (generated by console_contract.credential_assignment_js; do not edit)
  var CREDENTIAL_ASSIGNMENT_SOURCE = "(?:(?<![A-Za-z0-9_])(?:[aA][wW][sS][-_]?[sS][eE][cC][rR][eE][tT][-_]?[aA][cC][cC][eE][sS][sS][-_]?[kK][eE][yY]|[sS][eE][cC][rR][eE][tT][-_]?[aA][cC][cC][eE][sS][sS][-_]?[kK][eE][yY]|[aA][cC][cC][eE][sS][sS][-_]?[tT][oO][kK][eE][nN]|[rR][eE][fF][rR][eE][sS][hH][-_]?[tT][oO][kK][eE][nN]|[iI][dD][-_]?[tT][oO][kK][eE][nN]|[aA][uU][tT][hH][-_]?[tT][oO][kK][eE][nN]|[cC][lL][iI][eE][nN][tT][-_]?[sS][eE][cC][rR][eE][tT]|[pP][rR][iI][vV][aA][tT][eE][-_]?[kK][eE][yY]|[aA][pP][iI][-_]?[kK][eE][yY]|[aA][pP][iI][kK][eE][yY]|[tT][oO][kK][eE][nN]|[pP][aA][sS][sS][wW][oO][rR][dD]|[pP][aA][sS][sS][wW][dD]|[pP][wW][dD]|[sS][eE][cC][rR][eE][tT])(?![A-Za-z0-9_])|(?:\u5bc6\u7801|\u53e3\u4ee4|\u4ee4\u724c|\u5bc6\u94a5))[ \\t\\n\\r\\f\\v\\u00a0\\u1680\\u2000-\\u200a\\u2028\\u2029\\u202f\\u205f\\u3000]*[:=\uff1a][ \\t\\n\\r\\f\\v\\u00a0\\u1680\\u2000-\\u200a\\u2028\\u2029\\u202f\\u205f\\u3000]*(?:[^ \\t\\n\\r\\f\\v\\u00a0\\u1680\\u2000-\\u200a\\u2028\\u2029\\u202f\\u205f\\u3000]|(?![\\s\\S]))";
  var CREDENTIAL_ASSIGNMENT_RE = new RegExp(CREDENTIAL_ASSIGNMENT_SOURCE, 'i');
  // END CREDENTIAL_ASSIGNMENT_RE
  var URL_USERINFO_RE = /\b[a-z][a-z0-9+.-]*:\/\/[^\/\s:@]+:[^\/\s@]+@/i;
  var SHELL_COMMAND_RE = /(?:^|[\s;、(（])(?:curl|wget|Invoke-WebRequest|Invoke-Expression|iex|powershell|pwsh|cmd(?:\.exe)?|bash|sh|zsh|node|python3?|npm|npx|pnpm|yarn|git|docker|kubectl|ssh|scp|rm|rmdir|del|sudo|chmod|chown|eval|exec)\s+(?:-[^\s]+|\/|[A-Za-z0-9_.~\/\\])/i;
  var SHELL_PIPE_RE = /\|\s*(?:sh|bash|zsh|powershell|pwsh)\b/i;

  function isPlainObject(value) {
    return value !== null && typeof value === 'object' && !Array.isArray(value);
  }

  function own(object, key) {
    return Object.prototype.hasOwnProperty.call(object, key);
  }

  function hasOwnRole(value) {
    return typeof value === 'string' && own(ROLES, value);
  }

  function hasOwnExecutor(value) {
    return typeof value === 'string' && own(EXECUTORS, value);
  }

  function hasOwnMode(value) {
    return typeof value === 'string' && own(MODES, value);
  }

  function hasOwnWorkspace(value) {
    return value === 'worktree' || value === 'directory';
  }

  function idOf(value) {
    if (typeof value === 'string') {
      var trimmed = value.trim();
      return trimmed === '' ? null : trimmed;
    }
    if (typeof value === 'number' && isFinite(value)) {
      return String(value);
    }
    return null;
  }

  function stringifyValue(value) {
    if (value === null || value === undefined) {
      return null;
    }
    if (typeof value === 'string') {
      return value;
    }
    if (typeof value === 'number') {
      return isFinite(value) ? String(value) : null;
    }
    if (typeof value === 'boolean') {
      return null;
    }
    if (typeof value === 'bigint') {
      return String(value);
    }
    // 对象、数组、函数、symbol、NaN/Infinity 一律视为无文本，避免 [object Object]。
    return null;
  }

  function decodeOnce(text) {
    try {
      return decodeURIComponent(text);
    } catch (error) {
      return text.replace(/%([0-9A-Fa-f]{2})/g, function (_match, hex) {
        return String.fromCharCode(parseInt(hex, 16));
      });
    }
  }

  function decodeLayers(text) {
    var layers = [text];
    var current = text;
    var i;
    for (i = 0; i < 3; i += 1) {
      var next = decodeOnce(current);
      if (next === current) {
        break;
      }
      layers.push(next);
      current = next;
    }
    return layers;
  }

  // 与 console_contract._mentions_private 同口径：按词元/路径组件判断 private。
  // 单独一个 private 词元也拒绝；private.md、myprivate、prefix-private 不算组件。
  var PRIVATE_TOKEN_SPLIT_RE = /[\s"'`<>()\[\]{}|,;，。；：、]+/;
  var PRIVATE_EDGE_STRIP_RE = /^[.\-~!?*…·]+|[.\-~!?*…·]+$/g;
  var PRIVATE_PART_STRIP_RE = /^[.:]+|[.:]+$/g;

  function mentionsPrivateComponent(text) {
    var tokens = text.split(PRIVATE_TOKEN_SPLIT_RE);
    var i;
    for (i = 0; i < tokens.length; i += 1) {
      var token = tokens[i].replace(PRIVATE_EDGE_STRIP_RE, '');
      if (!token) {
        continue;
      }
      var parts = token.split(/[\\/]+/);
      var j;
      for (j = 0; j < parts.length; j += 1) {
        var part = parts[j].replace(PRIVATE_PART_STRIP_RE, '').toLowerCase();
        if (part === 'private') {
          return true;
        }
      }
    }
    return false;
  }

  function hasPrivatePathComponent(text) {
    if (mentionsPrivateComponent(text)) {
      return true;
    }
    // 与 Python 同步的路径上下文：中文无空格前缀、Markdown target 的 ?/#、
    // /private?query。候选已展开最多 3 层编码，这里不再递归解码。
    var normalized = text.replace(/\\/g, '/');
    if (/(?:^|[^A-Za-z0-9_.-])private(?=\/)/i.test(normalized)) {
      return true;
    }
    if (/\]\(\s*private(?=$|[/?#\s)])/i.test(normalized)) {
      return true;
    }
    return /\/private(?=[?#])/i.test(normalized);
  }

  function scanSensitiveText(text) {
    if (hasPrivatePathComponent(text)) {
      return true;
    }
    if (PEM_RE.test(text)) {
      return true;
    }
    if (AUTHORIZATION_RE.test(text) || BEARER_RE.test(text)) {
      return true;
    }
    if (CREDENTIAL_ASSIGNMENT_RE.test(text)) {
      return true;
    }
    if (URL_USERINFO_RE.test(text)) {
      return true;
    }
    // 可识别凭据：JWT、AWS、GitHub、Slack、Stripe、OpenAI/Anthropic、Google API key。
    if (/\beyJ[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}\b/.test(text)) {
      return true;
    }
    if (/\b(?:AKIA|ASIA)[0-9A-Z]{16}\b/.test(text)) {
      return true;
    }
    if (/\b(?:gh[pousr]_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{20,})\b/.test(text)) {
      return true;
    }
    if (/\bxox[abprs]-[A-Za-z0-9-]{10,}\b/.test(text)) {
      return true;
    }
    if (/\b(?:sk|pk)_(?:live|test)_[A-Za-z0-9]{16,}\b/.test(text)) {
      return true;
    }
    if (/\bsk-(?:ant-)?[A-Za-z0-9_-]{16,}\b/.test(text)) {
      return true;
    }
    if (/\bAIza[0-9A-Za-z_-]{30,}\b/.test(text)) {
      return true;
    }
    // 代码块 / 复杂命令不作为说明输出。
    if (/```|~~~/.test(text)) {
      return true;
    }
    if (/`[^`\n]*`/.test(text)) {
      return true;
    }
    if (/\$\(/.test(text) || /&&|\|\|/.test(text)) {
      return true;
    }
    if (SHELL_COMMAND_RE.test(text) || SHELL_PIPE_RE.test(text)) {
      return true;
    }
    return false;
  }

  function sensitiveCandidates(text) {
    // 原文 + 最多 3 层百分号解码；每层再看归一空白/移除控制字符变体，
    // 防止用编码、换行、零宽字符把敏感词或路径拆开绕过。
    var layers = decodeLayers(text);
    var candidates = [];
    var seen = Object.create(null);
    var i;
    for (i = 0; i < layers.length; i += 1) {
      var layer = layers[i];
      var variants = [
        layer,
        layer.replace(CONTROL_AND_INVISIBLE, ''),
        normalizeText(layer)
      ];
      var j;
      for (j = 0; j < variants.length; j += 1) {
        var variant = variants[j];
        if (variant && !own(seen, variant)) {
          seen[variant] = true;
          candidates.push(variant);
        }
      }
    }
    return candidates;
  }

  function looksSensitive(text) {
    var candidates = sensitiveCandidates(text);
    var i;
    for (i = 0; i < candidates.length; i += 1) {
      if (scanSensitiveText(candidates[i])) {
        return true;
      }
    }
    return false;
  }

  function stripMarkdownLinks(text) {
    var nestedTarget = '(?:[^()\\n]|\\([^()\\n]*\\))*';
    return text
      .replace(new RegExp('!\\[([^\\]\\n]*)\\]\\(' + nestedTarget + '\\)', 'g'), '$1')
      .replace(new RegExp('\\[([^\\]\\n]+)\\]\\(' + nestedTarget + '\\)', 'g'), '$1')
      .replace(/\[([^\]\n]+)\]\[[^\]\n]*\]/g, '$1')
      .replace(/^\s*\[[^\]\n]+\]:\s*\S+\s*$/g, '')
      .replace(/<[a-z][a-z0-9+.-]*:[^<>\s]+>/gi, '');
  }

  function normalizeText(text) {
    return text.replace(CONTROL_AND_INVISIBLE, ' ').replace(/\s+/g, ' ').trim();
  }

  function neutralizeLine(text) {
    return text
      .replace(/【\s*控制台指令\s*】/g, '《控制台指令》')
      .replace(/·/g, '、')
      .replace(/→/g, '->');
  }

  function truncate(text, limit, critical) {
    var chars = Array.from(text);
    if (chars.length <= limit) {
      return text;
    }
    if (critical) {
      return null;
    }
    return chars.slice(0, limit).join('').replace(/\s+$/, '') + TRUNCATION_SUFFIX;
  }

  function safeText(value, options) {
    var opts = options || {};
    var limit = typeof opts.limit === 'number' && isFinite(opts.limit) && opts.limit >= 0
      ? Math.floor(opts.limit)
      : TEXT_LIMIT;
    var raw = stringifyValue(value);
    if (raw === null) {
      return null;
    }
    // 与 Python 一致：超长原文直接拒绝；按 Unicode 码点计数。
    if (Array.from(raw).length > MAX_SAFE_TEXT_RAW) {
      return null;
    }
    // 敏感检查必须针对完整原文，限长/截断不能把敏感尾部藏掉。
    if (looksSensitive(raw)) {
      return null;
    }
    var text = normalizeText(stripMarkdownLinks(raw));
    if (text === '') {
      return null;
    }
    // 与 Python safe_text 一致：Markdown 目标去掉后，保留的 label 仍可能拼出敏感模式。
    if (looksSensitive(text)) {
      return null;
    }
    if (opts.lineEscape === true) {
      text = neutralizeLine(text);
    }
    return truncate(text, limit, opts.critical === true);
  }

  function safeLine(value, options) {
    var opts = Object.assign({}, options || {});
    opts.lineEscape = true;
    return safeText(value, opts);
  }

  function findRoleDefinition(roles, roleId) {
    if (Array.isArray(roles)) {
      var i;
      for (i = 0; i < roles.length; i += 1) {
        if (isPlainObject(roles[i]) && roles[i].id === roleId) {
          return roles[i];
        }
      }
      return null;
    }
    if (isPlainObject(roles) && isPlainObject(roles[roleId])) {
      return roles[roleId];
    }
    return null;
  }

  function defaultsFor(task, roles, environment, choice) {
    var t = isPlainObject(task) ? task : {};
    var c = isPlainObject(choice) ? choice : {};
    var envOk = isPlainObject(environment) && typeof environment.inOrca === 'boolean';
    var inOrca = envOk ? environment.inOrca : null;
    var reasons = [];
    var fallback = false;

    var roleId = hasOwnRole(c.roleId) ? c.roleId : (hasOwnRole(t.roleId) ? t.roleId : null);
    var executor = null;
    var mode = null;

    if (hasOwnExecutor(c.executor)) {
      executor = c.executor;
      reasons.push('用户选择执行器');
    }
    if (hasOwnMode(c.mode)) {
      if (envOk && inOrca && c.mode === 'terminal') {
        // PRD 在 Orca 内只提供新建工作区/现有目录；terminal 仅作非 Orca 强制项。
        reasons.push('Orca 内不支持新终端窗口');
      } else {
        mode = c.mode;
        reasons.push('用户选择工作区');
      }
    }

    if (!executor && hasOwnExecutor(t.declaredExecutor)) {
      executor = t.declaredExecutor;
      reasons.push('任务声明执行器');
    }

    if (!executor || !mode) {
      var prdRule = roleId && own(PRD_ROLE_DEFAULTS, roleId) ? PRD_ROLE_DEFAULTS[roleId] : null;
      if (prdRule) {
        var usedPrdRule = false;
        if (!executor) {
          executor = prdRule.executor;
          usedPrdRule = true;
        }
        if (!mode) {
          mode = prdRule.mode;
          usedPrdRule = true;
        }
        if (usedPrdRule) {
          reasons.push('PRD 角色规则：' + ROLES[roleId]);
        }
      } else if (roleId) {
        var definition = findRoleDefinition(roles, roleId);
        if (!executor && definition) {
          var firstExecutor = Array.isArray(definition.executors) ? definition.executors[0] : null;
          if (hasOwnExecutor(firstExecutor)) {
            executor = firstExecutor;
            reasons.push('角色配置：' + ROLES[roleId]);
          }
        }
        if (!mode && definition && hasOwnWorkspace(definition.workspace)) {
          mode = definition.workspace;
          reasons.push('角色配置工作区：' + ROLES[roleId]);
        }
      }
    }

    if (!executor) {
      if (t.changesCode === true) {
        executor = 'opencode';
        fallback = true;
        reasons.push('兜底：明确改代码');
      } else if (t.changesCode === false) {
        executor = 'claude';
        fallback = true;
        reasons.push('兜底：明确不改代码');
      }
    }

    if (!mode) {
      if (t.changesCode === true) {
        mode = 'worktree';
        reasons.push('改代码使用新建工作区');
      } else if (t.changesCode === false) {
        mode = 'directory';
        reasons.push('不改代码使用现有目录');
      }
    }

    if (!envOk) {
      // 缺少冻结环境时不能给出可派发的位置；执行器可保留供展示。
      mode = null;
      reasons.push('缺少环境信息');
    } else if (!inOrca) {
      if (mode !== 'terminal') {
        reasons.push('非 Orca 仅新终端窗口');
      }
      mode = 'terminal';
    }

    if (!executor) {
      reasons.push('证据不足：未确定执行器');
    }
    if (!mode) {
      reasons.push('证据不足：未确定工作区');
    }
    if (reasons.length === 0) {
      reasons.push('沿用任务默认');
    }

    return {
      executor: executor,
      mode: mode,
      reason: reasons.join('；'),
      fallback: fallback
    };
  }

  function choiceLabel(choices, choiceId) {
    if (!Array.isArray(choices)) {
      return null;
    }
    var i;
    for (i = 0; i < choices.length; i += 1) {
      var choice = choices[i];
      if (isPlainObject(choice) && choice.id === choiceId && typeof choice.label === 'string') {
        return choice.label;
      }
    }
    return null;
  }

  function exportPending(items, selections) {
    var root = isPlainObject(selections) ? selections : {};
    if (!isPlainObject(root.pending)) {
      return [];
    }
    var picks = root.pending;
    var lines = [];
    var seen = Object.create(null);
    var i;

    for (i = 0; i < items.length; i += 1) {
      var item = items[i];
      if (!isPlainObject(item)) {
        continue;
      }
      var id = idOf(item.id);
      if (id === null || seen[id]) {
        continue;
      }
      seen[id] = true;

      if (!own(picks, id) || !isPlainObject(picks[id])) {
        continue;
      }
      var pick = picks[id];
      if (!own(pick, 'choiceId') || typeof pick.choiceId !== 'string') {
        continue;
      }
      if (item.status !== PENDING_STATUSES.pending) {
        continue;
      }

      var prefix;
      var label;
      if (item.type === PENDING_TYPES.done) {
        if (!own(ACCEPT_CHOICES, pick.choiceId)) {
          continue;
        }
        prefix = '验收';
        label = ACCEPT_CHOICES[pick.choiceId];
      } else if (item.type === PENDING_TYPES.decision || item.type === PENDING_TYPES.blocked) {
        prefix = '拍板';
        label = choiceLabel(item.choices, pick.choiceId);
      } else {
        continue;
      }

      var project = safeLine(item.project);
      var subject = safeLine(item.item);
      var title = safeLine(item.title);
      if (project === null || subject === null || title === null) {
        continue;
      }
      var safeLabel = safeLine(label, { critical: true });
      if (safeLabel === null) {
        continue;
      }

      var line = '【控制台指令】' + prefix + '：' + project + '：' + subject + ' · ' + title + ' → ' + safeLabel;

      if (own(pick, 'note') && pick.note !== null && pick.note !== undefined) {
        if (typeof pick.note !== 'string') {
          continue;
        }
        if (pick.note.trim() !== '') {
          var note = safeLine(pick.note);
          if (note === null) {
            continue;
          }
          line += ' · 补充：' + note;
        }
      }

      lines.push(line);
    }

    return lines;
  }

  function isAbsoluteLocalPath(value) {
    if (typeof value !== 'string' || value === '') {
      return false;
    }
    if (value.indexOf('\\\\') === 0 || value.indexOf('//') === 0) {
      return false;
    }
    if (/^[A-Za-z]:[\\/]/.test(value)) {
      return true;
    }
    return value.charAt(0) === '/' && value.charAt(1) !== '/';
  }

  function hasParentTraversal(value) {
    return value.split(/[\\/]+/).some(function (part) {
      return part === '..';
    });
  }

  function exportDispatch(items, selections) {
    var root = isPlainObject(selections) ? selections : {};
    var environment = root.environment;
    var roleDefinitions = Array.isArray(root.roleDefinitions) ? root.roleDefinitions : [];
    if (!isPlainObject(environment) || typeof environment.inOrca !== 'boolean') {
      // 缺少当前冻结环境，任何派发都不能导出。
      return [];
    }
    if (!isPlainObject(root.dispatch)) {
      return [];
    }
    var picks = root.dispatch;
    var lines = [];
    var seen = Object.create(null);
    var i;

    for (i = 0; i < items.length; i += 1) {
      var item = items[i];
      if (!isPlainObject(item)) {
        continue;
      }
      var id = idOf(item.id);
      if (id === null || seen[id]) {
        continue;
      }
      seen[id] = true;

      if (!own(picks, id) || !isPlainObject(picks[id])) {
        continue;
      }
      var pick = picks[id];
      if (!own(pick, 'selected') || pick.selected !== true) {
        continue;
      }
      if (item.selectable !== true) {
        continue;
      }

      var project = safeLine(item.project);
      var taskNo = safeLine(item.taskNo);
      var title = safeLine(item.title);
      if (project === null || taskNo === null || title === null) {
        continue;
      }

      if (item.kind === 'delivery') {
        if (environment.inOrca !== true) {
          continue;
        }
        if (typeof item.prdPath !== 'string' || !isAbsoluteLocalPath(item.prdPath) || hasParentTraversal(item.prdPath)) {
          continue;
        }
        if (/[\u0000-\u001F\u007F]/.test(item.prdPath)) {
          continue;
        }
        if (safeLine(item.prdPath) === null) {
          continue;
        }
        lines.push('【控制台指令】确认派发：' + project + '：' + taskNo + ' ' + title + ' · 开发交付流水线');
        continue;
      }

      if (item.kind !== 'single') {
        continue;
      }

      var choice = {};
      if (own(pick, 'roleId') && pick.roleId !== null && pick.roleId !== undefined) {
        if (!hasOwnRole(pick.roleId)) {
          continue;
        }
        choice.roleId = pick.roleId;
      }
      if (own(pick, 'executor') && pick.executor !== null && pick.executor !== undefined) {
        if (!hasOwnExecutor(pick.executor)) {
          continue;
        }
        choice.executor = pick.executor;
      }
      if (own(pick, 'mode') && pick.mode !== null && pick.mode !== undefined) {
        if (!hasOwnMode(pick.mode)) {
          continue;
        }
        if (environment.inOrca === true && pick.mode === 'terminal') {
          // Orca 内不提供新终端窗口；旧选择/手工改 DOM 不能绕过导出校验。
          continue;
        }
        choice.mode = pick.mode;
      }

      var defaults = defaultsFor(item, roleDefinitions, environment, choice);
      if (defaults.executor === null || defaults.mode === null) {
        continue;
      }
      var executor = defaults.executor;
      var mode = defaults.mode;
      if (environment.inOrca !== true) {
        // 双校验：即使旧选择手工改成 worktree/directory，非 Orca 也只能新终端窗口。
        mode = 'terminal';
      } else if (mode === 'terminal') {
        // Orca 内 terminal 不是允许的 PRD 地点，拒绝导出而不是静默换位置。
        continue;
      }
      var effectiveRoleId = hasOwnRole(choice.roleId)
        ? choice.roleId
        : (hasOwnRole(item.roleId) ? item.roleId : null);
      var roleLabel = effectiveRoleId === null ? '未指定' : ROLES[effectiveRoleId];

      lines.push(
        '【控制台指令】确认派发：' + project + '：' + taskNo + ' ' + title +
        ' · 角色 ' + roleLabel +
        ' · 执行器 ' + EXECUTORS[executor] +
        ' · ' + MODES[mode]
      );
    }

    return lines;
  }

  function exportRoles(items, selections) {
    var root = isPlainObject(selections) ? selections : {};
    if (!isPlainObject(root.roles)) {
      return [];
    }
    var picks = root.roles;
    var lines = [];
    var seen = Object.create(null);
    var i;

    for (i = 0; i < items.length; i += 1) {
      var item = items[i];
      if (!isPlainObject(item)) {
        continue;
      }
      var id = idOf(item.id);
      if (id === null || seen[id]) {
        continue;
      }
      seen[id] = true;

      if (!hasOwnRole(id)) {
        continue;
      }
      if (!own(picks, id) || !isPlainObject(picks[id])) {
        continue;
      }
      var pick = picks[id];
      if (!own(pick, 'action') || typeof pick.action !== 'string') {
        continue;
      }
      var name = safeLine(item.name);
      if (name === null) {
        continue;
      }

      if (pick.action === 'activate') {
        lines.push('【控制台指令】角色：' + name + ' → 转正（改为 active）');
        continue;
      }

      if (pick.action === 'executor') {
        if (!own(pick, 'executor') || !hasOwnExecutor(pick.executor)) {
          continue;
        }
        lines.push('【控制台指令】角色：' + name + ' → 换主装备 → ' + EXECUTORS[pick.executor]);
        continue;
      }

      if (pick.action === 'feedback') {
        if (!own(pick, 'note') || typeof pick.note !== 'string' || pick.note.trim() === '') {
          continue;
        }
        var note = safeLine(pick.note);
        if (note === null) {
          continue;
        }
        lines.push('【控制台指令】角色：' + name + ' → 修改意见：' + note);
      }
    }

    return lines;
  }

  function exportLines(kind, items, selections) {
    if (kind !== 'pending' && kind !== 'dispatch' && kind !== 'roles') {
      throw new TypeError('未知导出类型：' + String(kind));
    }
    if (!Array.isArray(items)) {
      return [];
    }
    if (kind === 'pending') {
      return exportPending(items, selections);
    }
    if (kind === 'dispatch') {
      return exportDispatch(items, selections);
    }
    return exportRoles(items, selections);
  }

