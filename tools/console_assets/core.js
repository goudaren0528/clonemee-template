  function validateReply(slot, quick, text) {
    if (!isPlainObject(slot)) {
      return { ok: false, code: 'bad_card' };
    }
    if (slot.allowed !== true) {
      return { ok: false, code: slot.reason === 'other_device' ? 'other_device' : 'not_replyable' };
    }
    var raw = text === null || text === undefined ? '' : text;
    if (typeof raw !== 'string') {
      return { ok: false, code: 'bad_json' };
    }
    var body = raw.trim();
    if (Array.from(body).length > REPLY_LIMITS.maxChars) {
      return { ok: false, code: 'too_long' };
    }
    var hasQuick = quick !== null && quick !== undefined;
    if (hasQuick) {
      var ids = replyChoices(slot).map(function (choice) { return choice.id; });
      if (typeof quick !== 'string' || ids.indexOf(quick) === -1) {
        return { ok: false, code: 'bad_choice' };
      }
      if (listOf(slot.pageOnly).indexOf(quick) !== -1) {
        return { ok: false, code: 'page_only' };
      }
    }
    if (!hasQuick && body === '') {
      return { ok: false, code: 'empty' };
    }
    if (hasQuick && listOf(slot.needText).indexOf(quick) !== -1 && body === '') {
      return { ok: false, code: 'need_text' };
    }
    if (body !== '' && safeText(body) === null) {
      return { ok: false, code: 'sensitive' };
    }
    return { ok: true, code: null };
  }

