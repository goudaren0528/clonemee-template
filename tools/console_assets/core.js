/*
 * AssistantConsole core (P0) — 纯逻辑、无 DOM、无网络、无存储、无 eval。
 *
 * 全局入口：
 *   window.AssistantConsole（Node vm 无 window 时挂到 globalThis）
 *
 * 公开 API：
 *   safeText(value, options?)                 安全文本；敏感值返回 null
 *   safeLine(value, options?)                 安全单行；额外中和指令标记与结构分隔符
 *   exportLines(kind, items, selections)      按当前页合法选择导出中文指令
 *   defaultsFor(task, roles, environment, choice?) -> {executor, mode, reason, fallback}
 *   registerPage(id, {mount})                 注册固定四页之一；重复注册报错
 *   v1.1 回复（与 console_contract 同口径，契约测试比对两边常量）：
 *   replyChoices(slot)                        -> 这张卡片的快捷评价 [{id, label}]
 *   validateReply(slot, quick, text)          -> {ok, code}；code 同 REPLY_ERROR_CODES，另有 page_only
 *   replyCommandLine(view, quick, text)       -> 通道没开时复制的【控制台指令】回复：… 一行，或 null
 *   getPage(id)                               读取已注册页面
 *   pages                                     页面注册表（pending/dispatch/runs/roles）
 *
 * 选择形状（selections，P0 冻结）：
 *   {
 *     pending:  { [itemId]: {choiceId, note?} },
 *     dispatch: { [itemId]: {selected:true, roleId?, executor?, mode?} },
 *     roles:    { [roleId]: {action:'activate'|'executor'|'feedback', executor?, note?} },
 *     environment: {inOrca:boolean, executorsAvailable?:string[]},
 *     roleDefinitions: Role[]
 *   }
 *
 * 常量：
 *   执行器 claude / codex / opencode -> Claude Code / Codex / OpenCode
 *   模式   worktree / directory / terminal -> 新建工作区 / 现有目录 / 新终端窗口
 *   角色   research / product / pm / investigate / dev / accept
 *          -> 调研 / 产品 / 跟进 / 排查 / 开发 / 验收
 *   页面   pending / dispatch / runs / roles
 *   验收   accept / reject / later -> 验收通过 / 打回 / 稍后
 *   文本   原文上限 20000 Unicode 码点；500 码点截断后追加 ［已截断］
 *
 * 优先级：用户选择 > 任务声明执行器 > PRD 四角色映射
 *         > PRD 未定义角色的配置（executors[0] + 可选 workspace）
 *         > 有明确 changesCode 兜底；不从标题猜角色；非 Orca 强制 terminal。
 */
